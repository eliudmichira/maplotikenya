/**
 * Evaluates whether a property matches a search query, with strict distinction
 * between "Thika Road" (the transit corridor) and "Thika" (Thika town).
 */
export function matchesPropertySearch(property, query) {
  if (!query || !query.trim()) return true;
  const q = query.toLowerCase().trim();

  const title = (property.title || '').toLowerCase();
  const desc = (property.description || '').toLowerCase();
  const area = (property.location?.area || property.area || property.location?.address || property.address || '').toLowerCase();
  const city = (property.location?.city || property.city || '').toLowerCase();
  const county = (property.location?.county || property.county || '').toLowerCase();
  const estate = (property.location?.estate || property.estate || '').toLowerCase();
  const neighborhood = (typeof property.neighborhood === 'string' ? property.neighborhood : property.neighborhood?.name || '').toLowerCase();

  const allText = `${title} ${area} ${city} ${county} ${estate} ${neighborhood} ${desc}`;

  const isQueryThikaRoad = /\bthika\s*(?:road|rd|superhighway)\b/i.test(q);
  const isQueryThikaTown = /\bthika\b/i.test(q) && !isQueryThikaRoad;

  if (isQueryThikaRoad) {
    // 1. User searched "Thika Road"
    // Match properties explicitly in Thika Road corridor
    const isCorridorProperty =
      area.includes('thika road') ||
      area.includes('thika superhighway') ||
      title.includes('thika road') ||
      title.includes('thika superhighway') ||
      desc.includes('thika road') ||
      desc.includes('thika superhighway') ||
      desc.includes('thika rd') ||
      /\b(garden city|safari park|safaripark|usiu|roasters|mirema|roysambu|kasarani|clay city|kahawa sukari|kahawa wendani|kenyatta road)\b/i.test(area) ||
      /\b(garden city|safari park|safaripark|usiu|roasters|mirema|roysambu|kasarani|clay city|kahawa sukari|kahawa wendani|kenyatta road)\b/i.test(title);

    if (!isCorridorProperty) return false;

    // Must NOT be exclusively in Thika town
    const isStrictlyThikaTown = /\b(thika town|section 9|section nine|makongeni|landless|ngoingwa|thika cbd)\b/i.test(area + ' ' + title);
    if (isStrictlyThikaTown) return false;

    // Check remaining words in query
    const remainingWords = q.replace(/\bthika\s*(?:road|rd|superhighway)\b/gi, '').trim().split(/[\s,]+/).filter(Boolean);
    if (remainingWords.length === 0) return true;
    return remainingWords.every(w => allText.includes(w));
  }

  if (isQueryThikaTown) {
    // 2. User searched "Thika" specifically (Thika Town)
    // Exclude corridor properties that are not in Thika town
    const isCorridorProperty =
      (area.includes('thika road') || title.includes('thika road') || desc.includes('thika road')) &&
      !/\b(thika town|section 9|section nine|makongeni|landless|ngoingwa|thika cbd|del monte|chania)\b/i.test(allText);

    if (isCorridorProperty) return false;

    // Must be in Thika town/area
    const isThika =
      area === 'thika' ||
      area === 'thika town' ||
      /\bthika\b/i.test(area) ||
      /\b(thika town|thika cbd|section 9|section nine|makongeni|landless|ngoingwa|del monte|chania)\b/i.test(title) ||
      /\b(thika town|thika cbd|section 9|section nine|makongeni|landless|ngoingwa|del monte|chania)\b/i.test(desc);

    if (!isThika) return false;

    // Check remaining words in query
    const remainingWords = q.replace(/\bthika\b/gi, '').trim().split(/[\s,]+/).filter(Boolean);
    if (remainingWords.length === 0) return true;
    return remainingWords.every(w => allText.includes(w));
  }

  // 3. General query: all search words must match
  const words = q.split(/[\s,]+/).filter(Boolean);
  return words.every(w => allText.includes(w));
}
