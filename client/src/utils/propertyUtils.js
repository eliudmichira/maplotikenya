/**
 * Maploti - Property Data Sanitization & Deduplication Utilities
 * 
 * Provides robust guards for:
 * 1. Deduplicating clone properties across search, map, and grid views.
 * 2. Correcting micro-prices (e.g. 2, 3, 25, 40, 75, 150) from shorthand "k" / "M" inputs.
 * 3. Enforcing correct listingType ('rent' vs 'sale') so sale properties never display "/month".
 * 4. Normalizing land/floor area sizes (acres vs m2).
 * 5. Formatting bedroom and bathroom labels distinctly to avoid digit concatenation (e.g. "32").
 */

/**
 * Derives the clean listing type ('rent' or 'sale')
 */
export function deriveListingType(p) {
  if (!p) return 'rent';
  if (p.id && VERIFIED_INSTAGRAM_PRICES[p.id]?.listingType) {
    return VERIFIED_INSTAGRAM_PRICES[p.id].listingType;
  }
  const title = String(p.title || '').toLowerCase();
  const desc = String(p.description || '').toLowerCase();
  const rawType = String(p.listingType || p.listing_type || p.purpose || p.type || '').toLowerCase();
  const price = Number(p.price) || 0;

  // 1. Explicit title indicator takes priority
  if (/for sale|house for sale|apartment for sale|plots? for sale|villa for sale|mansionette.*sale|townhouse.*sale/i.test(title)) {
    return 'sale';
  }
  if (/to let|for rent|rental/i.test(title)) {
    return 'rent';
  }

  // 2. High-value property with sale keywords in description
  if (price > 1500000 && !/to let|for rent|per month|\/month/i.test(title + ' ' + desc)) {
    return 'sale';
  }

  // 3. Raw category fields
  if (/sale|sell|buy/.test(rawType)) return 'sale';
  if (/rent|let/.test(rawType)) return 'rent';

  // 4. Description cues
  if (/for sale|buy/i.test(desc) && !/to let|for rent/i.test(desc)) return 'sale';
  if (/to let|per month|\/month/i.test(desc)) return 'rent';

  return 'rent';
}

/**
 * Sanitizes micro-prices (e.g. 3 -> 3,300,000, 150 -> 150,000) using description cues or multipliers
 */
export function sanitizePrice(p) {
  if (!p) return 0;
  if (p.id && VERIFIED_INSTAGRAM_PRICES[p.id]?.price) {
    return VERIFIED_INSTAGRAM_PRICES[p.id].price;
  }
  let price = Number(p.price) || 0;
  if (!Number.isFinite(price) || price <= 0) return 0;

  const desc = String(p.description || '');
  const title = String(p.title || '');
  const type = deriveListingType(p);

  // Micro-price detection or corrupted sale prices (e.g. 2000 for sale when text says KES 2.5M)
  if (price <= 500 || (price < 500000 && (type === 'sale' || /sale/i.test(title)))) {
    // 1. Check for million expressions in description: e.g. "3.3 million", "15 million", "2.5M", "KES 2.5M"
    const mMatch = desc.match(/(?:ksh|kes|price:?|from)?\s*([0-9]+(?:\.[0-9]+)?)\s*(?:m\b|million)/i);
    if (mMatch) {
      return Math.round(parseFloat(mMatch[1]) * 1000000);
    }

    // 2. Check for thousand / "k" expressions in description: e.g. "@ 150k", "@ 40k", "75k per month"
    const kMatch = desc.match(/(?:@|at|kes|ksh|price:?)?\s*([0-9]{2,3})\s*(?:k\b|thousand)/i);
    if (kMatch) {
      return Math.round(parseFloat(kMatch[1]) * 1000);
    }

    // 3. Intelligent fallback multiplier if price is single or double digits
    if (price <= 500) {
      if (type === 'sale' || /sale/i.test(title)) {
        return price * 1000000; // e.g. 15 -> 15M, 2 -> 2M
      } else {
        return price * 1000; // e.g. 40 -> 40k, 150 -> 150k
      }
    }
  }

    // Scraper fallback fix: 1 Bedroom at Northland Heights has rent of Ksh 45,000
  if (price === 85000 && /northland/i.test(title + ' ' + desc) && (p.bedrooms === 1 || /1\s*bed/i.test(title))) {
    return 45000;
  }

  // Edge case: "150,000 4 Bedroom Maisonette for sale" -> intended 15,000,000 or rental
  if (price === 150000 && /maisonette.*sale|house.*sale|villa.*sale/i.test(title)) {
    return 15000000;
  }

  return price;
}

/**
 * Formats land and floor area measurements
 */
export function formatPropertyArea(p) {
  if (!p) return '';
  const title = String(p.title || '');

  // Acre detection
  if (/acre/i.test(title)) {
    if (/1\/4\s*(?:th)?\s*acre/i.test(title)) return '0.25 Acres';
    if (/1\/2\s*acre|half\s*acre/i.test(title)) return '0.5 Acres';
    if (/1\/8\s*(?:th)?\s*acre/i.test(title)) return '0.125 Acres';
    if (/3\/4\s*acre/i.test(title)) return '0.75 Acres';
    const match = title.match(/([0-9]+(?:\.[0-9]+)?)\s*acres?/i);
    if (match) return `${match[1]} Acres`;
  }

  if (p.size && /acre|50\s*x\s*100|40\s*x\s*80/i.test(String(p.size))) {
    return String(p.size);
  }

  const sqm = Number(p.sizeSqm || p.area_sqm || p.area || 0);
  if (sqm > 0) {
    const beds = Number(p.bedrooms) || 0;
    // Glitch check: 1BR or Studio claiming 1,000+ m2 is likely a square foot or typo
    if (beds <= 1 && sqm >= 500) {
      return '';
    }
    return `${sqm.toLocaleString()} m²`;
  }

  return '';
}

